/**
 * MapLegend component.
 *
 * A Legend explains the meaning of visual elements shown on the map.
 * In this case, it helps the user understand:
 * - Color coding (e.g. wind intensity levels)
 * - Symbols or arrows (e.g. wind direction)
 * - Possible thresholds (e.g. low / medium / high risk)
 *
 * Responsibility:
 * - Visually describe how map data is represented
 * - Provide short explanations for colors, gradients or icons
 * - Improve interpretability of hazard and weather layers
 *
 * Why:
 * Without a legend, users may misinterpret map visualizations.
 * The legend increases usability, clarity and trust in the data presented.
 */